CREATE TABLE chat_messages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 interest_id VARCHAR(36) NOT NULL REFERENCES interests(id) ON DELETE CASCADE,
 sender_id VARCHAR(36) NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
 body VARCHAR(2000) NOT NULL, client_message_id VARCHAR(36) NOT NULL,
 created_at VARCHAR(40) NOT NULL,
 UNIQUE(interest_id,sender_id,client_message_id)
);
CREATE INDEX chat_messages_conversation ON chat_messages(interest_id,id);
CREATE INDEX chat_messages_sender ON chat_messages(sender_id,created_at);
CREATE TABLE chat_reads (
 interest_id VARCHAR(36) NOT NULL REFERENCES interests(id) ON DELETE CASCADE,
 owner_id VARCHAR(36) NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
 last_message_id BIGINT NOT NULL DEFAULT 0,
 PRIMARY KEY(interest_id,owner_id)
);
